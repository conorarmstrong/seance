"""Independent Windows 11 ARM64 (build 28000) kernel-half walker and sampler for MEM-ARM-8.

    python3 scripts/oracle/winarm_walk.py MEM_RAW   (run from the repository root; MEM_RAW is a raw capture of the guest)

Written from ARM DDI 0487 D8 and the `_MMPTE_*` layouts in Microsoft's PDB for the build, without
reference to the Rust walker. Draws 240 addresses by random descent (seed 28000) and writes
seance_memory/tests/winarm_28000_samples.in.
"""
import mmap,struct,random,json,collections,sys
f=open(sys.argv[1],'rb');m=mmap.mmap(f.fileno(),0,access=mmap.ACCESS_READ)
def rd(pa):return struct.unpack_from('<Q',m,pa)[0]
ROOT=0x14dbdd800
def translate(va):
    """independent walker: 4 KiB granule, 47-bit TTBR1, layouts from the PDB"""
    assert va>>47==0x1ffff
    idx=[(va>>39)&0xff,(va>>30)&0x1ff,(va>>21)&0x1ff,(va>>12)&0x1ff]
    tab=ROOT
    for lvl in range(4):
        ea=tab+8*idx[lvl];e=rd(ea)
        if e&1:
            if lvl==3:
                if e&2:return ('page',(e&0xfffffffff000)|(va&0xfff),0x1000,lvl,e,ea)
                return ('absent',lvl,e,ea)
            if e&2:tab=e&0xfffffffff000;continue
            if lvl==2:sz=1<<21;return ('block',(e&0xffffffe00000)|(va&(sz-1)),sz,lvl,e,ea)
            return ('other',lvl,e,ea)
        if e and e&(1<<11) and not e&(1<<10):
            nt=(e>>12&((1<<40)-1))<<12
            if lvl==3:return ('transition',nt|(va&0xfff),0x1000,lvl,e,ea)
            tab=nt;continue
        if e&(1<<10):return ('prototype',lvl,e,ea)
        if e>>32:return ('pagefile',lvl,e,ea)
        return ('absent',lvl,e,ea)
def rand_va(rng):
    tab=ROOT;va=0xffff800000000000
    for lvl in range(4):
        n=256 if lvl==0 else 512
        for _ in range(64):
            i=rng.randrange(n);e=rd(tab+8*i)
            if e:break
        sh=39-9*lvl;va|=i<<sh
        if lvl==3:break
        if e&1 and e&2:tab=e&0xfffffffff000
        elif e&1==0 and e&(1<<11) and not e&(1<<10):tab=(e>>12&((1<<40)-1))<<12
        else:break
        if tab+4096>len(m):break
    return va|rng.randrange(1<<(39-9*lvl if lvl<3 else 12)) if lvl<3 else va|rng.randrange(4096)
rng=random.Random(28000);want={'page':60,'block':20,'transition':40,'pagefile':40,'prototype':40,'absent':40}
got=collections.defaultdict(list);tries=0
while any(len(got[k])<v for k,v in want.items()) and tries<3_000_000:
    tries+=1;va=rand_va(rng)
    try:r=translate(va)
    except AssertionError:continue
    k=r[0]
    if k in want and len(got[k])<want[k]:got[k].append((va,r))
out=[]
for k in want:
    for va,r in got[k]:
        if k in('page','block','transition'):out.append((va,k,r[1],r[2],r[4]))
        else:out.append((va,k,r[1],0,r[2]))   # lvl, 0, entry
print({k:len(v) for k,v in got.items()},tries)
open('samples.json','w').write(json.dumps(out))
with open('seance_memory/tests/winarm_28000_samples.in','w') as fh:
    fh.write("// Generated by forensic_corpora/winarm_28000_qemu/samples.py: (va, kind, pa-or-level, run_len, entry).\n&[\n")
    for va,k,a,sz,e in out:fh.write(f'    ({va:#x}, "{k}", {a:#x}, {sz:#x}, {e:#x}),\n')
    fh.write("]\n")
