"""Independent Windows 11 ARM64 kernel-half walker and sampler (4 KiB granule, 47-bit TTBR1) for a capture whose file offset 0 is physical RAM_BASE.

    python3 scripts/oracle/winarm_walk_ram.py MEM_RAW RAM_BASE TTBR1_ROOT SEED OUT_IN

Written from ARM DDI 0487 D8 and the `_MMPTE_*` layouts in Microsoft's PDB for the captured kernel, without reference to the Rust walker.
It is `winarm_walk.py` with the capture as arguments, so it can grade a build other than 28000. Draws 240 addresses by random descent
and writes the Rust samples file `(va, kind, pa-or-level, run_len, entry)`. Layout facts it uses, for kernel `ntkrnlmp.pdb`
GUID 7A9F162A39E89C67CD02CF2126D51A65 (build 26300.9457): `Prototype` bit 10, `Transition` bit 11, `PageFileHigh` bits 63:32.
It also prints how many pagefile entries carry a non-zero `PageFileLow` (bits 9:6 on that build; bits 17:14 on build 28000).
"""
import mmap, struct, random, sys, collections
mem, base, root, seed, out_path = sys.argv[1], int(sys.argv[2], 0), int(sys.argv[3], 0), int(sys.argv[4]), sys.argv[5]
f = open(mem, 'rb'); m = mmap.mmap(f.fileno(), 0, access=mmap.ACCESS_READ)
def rd(pa):
    o = pa - base
    return struct.unpack_from('<Q', m, o)[0] if 0 <= o <= len(m) - 8 else None
def translate(va):
    idx = [(va >> 39) & 0xff, (va >> 30) & 0x1ff, (va >> 21) & 0x1ff, (va >> 12) & 0x1ff]
    tab = root
    for lvl in range(4):
        ea = tab + 8 * idx[lvl]; e = rd(ea)
        if e is None: return ('absent', lvl, 0, ea)
        if e & 1:
            if lvl == 3:
                if e & 2: return ('page', (e & 0xfffffffff000) | (va & 0xfff), 0x1000, lvl, e, ea)
                return ('absent', lvl, e, ea)
            if e & 2: tab = e & 0xfffffffff000; continue
            if lvl == 2:
                sz = 1 << 21; return ('block', (e & 0xffffffe00000) | (va & (sz - 1)), sz, lvl, e, ea)
            return ('other', lvl, e, ea)
        if e and e & (1 << 11) and not e & (1 << 10):
            nt = (e >> 12 & ((1 << 40) - 1)) << 12
            if lvl == 3: return ('transition', nt | (va & 0xfff), 0x1000, lvl, e, ea)
            tab = nt; continue
        if e & (1 << 10): return ('prototype', lvl, e, ea)
        if e >> 32: return ('pagefile', lvl, e, ea)
        return ('absent', lvl, e, ea)
    return ('absent', 3, 0, 0)
def rand_va(rng):
    tab = root; va = 0xffff800000000000
    for lvl in range(4):
        n = 256 if lvl == 0 else 512
        e = None
        for _ in range(64):
            i = rng.randrange(n); e = rd(tab + 8 * i)
            if e: break
        sh = 39 - 9 * lvl; va |= i << sh
        if lvl == 3: break
        if e is None: return None
        if e & 1 and e & 2: tab = e & 0xfffffffff000
        elif e & 1 == 0 and e & (1 << 11) and not e & (1 << 10): tab = (e >> 12 & ((1 << 40) - 1)) << 12
        else: break
        if tab - base + 4096 > len(m): break
    return va | rng.randrange(1 << (39 - 9 * lvl)) if lvl < 3 else va | rng.randrange(4096)
rng = random.Random(seed); want = {'page': 60, 'block': 20, 'transition': 40, 'pagefile': 40, 'prototype': 40, 'absent': 40}
got = collections.defaultdict(list); tries = 0
while any(len(got[k]) < v for k, v in want.items()) and tries < 3_000_000:
    tries += 1; va = rand_va(rng)
    if va is None: continue
    r = translate(va); k = r[0]
    if k in want and len(got[k]) < want[k]: got[k].append((va, r))
low = collections.Counter(((r[2] >> 6) & 0xf) for va, r in got['pagefile'])
print({k: len(v) for k, v in got.items()}, tries, "PageFileLow(9:6) of the sampled pagefile entries:", dict(low))
with open(out_path, 'w') as fh:
    fh.write("// Generated by scripts/oracle/winarm_walk_ram.py: (va, kind, pa-or-level, run_len, entry).\n&[\n")
    for k in want:
        for va, r in got[k]:
            if k in ('page', 'block', 'transition'): fh.write(f'    ({va:#x}, "{k}", {r[1]:#x}, {r[2]:#x}, {r[4]:#x}),\n')
            else: fh.write(f'    ({va:#x}, "{k}", {r[1]:#x}, 0x0, {r[2]:#x}),\n')
    fh.write("]\n")
