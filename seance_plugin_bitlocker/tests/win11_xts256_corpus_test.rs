//! Known-answer test against a REAL modern Windows 11 BitLocker system volume.
//!
//! `bdetogo.raw` — the only other BitLocker sample in the tree — is a
//! Vista/7-era **AES-CBC 128 + Elephant diffuser** BitLocker-To-Go volume on a
//! FAT partition. Every Windows release since 2015 writes **AES-XTS** instead,
//! on a GPT system volume, unlocked by a TPM or a 48-digit recovery password.
//! Until this test, `src/xts.rs` had no real-image evidence behind it at all:
//! the XTS path was exercised only by synthetic vectors.
//!
//! The image is a Windows 11 25H2 Enterprise Evaluation install (build 26200),
//! encrypted with XTS-AES-256 over the whole volume, built specifically as a
//! corpus. It is large (64 GiB) and therefore not in the repository; set
//! `SEANCE_WIN11_BITLOCKER_IMAGE` to its path to run these.
//!
//! What makes this a *known-answer* test rather than a smoke test: the
//! recovery password below was generated by Windows, and the plaintext
//! assertions are structures Windows wrote — an NTFS boot sector and an MFT
//! record. Nothing here is asserted against this implementation's own output.

use seance_core::artifact::{Artifact, ArtifactType};
use seance_core::credential::{self, CredentialKind, CredentialOutcome, RunCredential};
use seance_core::data_source::{DataSource, FileDataSource, WindowSource};
use seance_core::module::ForensicsModule;
use seance_plugin_bitlocker::{
    is_bitlocker, unlock_bitlocker, BitlockerDecryptor, Credential, EncryptionMethod,
};
use std::sync::Arc;

/// Byte offset of the BitLocker-protected Windows partition within the disk
/// image, from the image's GPT. The partition begins with `-FVE-FS-` at +3.
const VOLUME_OFFSET: u64 = 407_896_064;

/// Size of that partition, 61.52 GiB.
const VOLUME_LENGTH: u64 = 66_060_288_000;

/// Where BitLocker relocated this volume's original NTFS boot sector.
///
/// Sector 0 of a BitLocker volume holds BitLocker's own VBR in plaintext, not
/// the filesystem's. The real volume header — 8192 bytes of it — is moved
/// elsewhere and encrypted, and the FVE metadata records where in its
/// "volume header block" entry (type `0x000f`): offset `0x37e9000`, size 8192
/// for this image.
///
/// `BitlockerXtsDataSource` decrypts verbatim by offset and does not remap
/// this, so a caller reading offset 0 of the decrypted view gets noise. That is
/// worth knowing when handing the decrypted source to a filesystem parser.
const RELOCATED_HEADER_OFFSET: u64 = 58_626_048;

/// The recovery password Windows generated for this volume.
///
/// It is the *only* way into the image. The volume also carries a TPM
/// protector, but that seals the VMK inside the emulated TPM's state on the
/// machine that built the corpus — it is not in the image, exactly as a real
/// seized disk carries no way to unseal without its motherboard.
const RECOVERY_PASSWORD: &str = "633281-498102-426096-319726-225203-245927-337876-444884";

/// Resolve a corpus file, preferring an explicit environment override and
/// otherwise looking where the repository keeps its gitignored corpus.
///
/// Cargo runs a test binary with the *package* directory as its working
/// directory, not the workspace root, so a bare `test_data/...` path does not
/// exist and every test using it skips silently while reporting "ok". That is
/// worse than failing: the suite is green and nothing ran.
fn corpus_path(env_var: &str, name: &str) -> Option<std::path::PathBuf> {
    if let Ok(p) = std::env::var(env_var) {
        let p = std::path::PathBuf::from(p);
        return p.exists().then_some(p);
    }
    let cwd = std::env::current_dir().ok()?;
    let root = if cwd.ends_with("seance_plugin_bitlocker") {
        cwd.parent()?.to_path_buf()
    } else {
        cwd
    };
    let p = root.join("test_data/win11_bitlocker").join(name);
    p.exists().then_some(p)
}

fn image_path() -> Option<std::path::PathBuf> {
    corpus_path("SEANCE_WIN11_BITLOCKER_IMAGE", "win11-bitlocker-xts256.raw")
}

fn volume() -> Option<Arc<dyn DataSource>> {
    let disk: Arc<dyn DataSource> = Arc::new(FileDataSource::new(image_path()?).ok()?);
    Some(Arc::new(WindowSource::new(
        disk,
        VOLUME_OFFSET,
        VOLUME_LENGTH,
    )))
}

/// The decrypted volume, which is what a filesystem parser would be handed.
fn decrypted_volume() -> Option<Arc<dyn DataSource>> {
    let unlocked = unlock_bitlocker(
        volume()?,
        &Credential::RecoveryKey(RECOVERY_PASSWORD.into()),
    )
    .expect("unlock");
    unlocked.decrypting_source
}

macro_rules! require_image {
    () => {
        match volume() {
            Some(v) => v,
            None => {
                eprintln!(
                    "skipping: set SEANCE_WIN11_BITLOCKER_IMAGE to the Windows 11 \
                     BitLocker corpus image to run this test"
                );
                return;
            }
        }
    };
}

/// The partition must be recognised through a window into a whole-disk image,
/// which is how it actually arrives — not as a bare volume file.
#[test]
fn a_windows_11_system_volume_is_detected_as_bitlocker() {
    let vol = require_image!();
    assert!(
        is_bitlocker(vol.as_ref()),
        "the GPT partition at offset {VOLUME_OFFSET} must detect as BitLocker"
    );
}

/// **The point of this test.** A 48-digit recovery password is a different key
/// derivation from a user password: the digits are checked against their
/// divisibility rule, divided by 11, and reassembled into key material before
/// the SHA-256 chain runs. `bdetogo.raw` exercises the password path only, so
/// this is the first real-image evidence for the recovery-key path.
#[test]
fn the_recovery_password_unlocks_a_real_xts_volume() {
    let vol = require_image!();

    let unlocked = unlock_bitlocker(vol, &Credential::RecoveryKey(RECOVERY_PASSWORD.into()))
        .expect("the recovery password must unlock this volume");

    assert_eq!(
        unlocked.encryption_method,
        EncryptionMethod::AesXts256,
        "this corpus is XTS-AES-256; a different answer means the FVE cipher \
         identifier was misread"
    );
    assert_eq!(
        unlocked.fvek.len() % 16,
        0,
        "an XTS FVEK is a whole number of AES keys"
    );
    assert!(
        unlocked.decrypting_source.is_some(),
        "an XTS volume must expose a decrypting source"
    );
}

/// A wrong credential must fail, and must fail *because the MAC rejected it* —
/// `BadCredential`, not `NotBitlocker` or a parse error. Without pinning the
/// error, this test passes on any failure at all: it passed against a volume
/// this build could not even recognise, which proved nothing about the
/// credential check.
#[test]
fn a_wrong_recovery_password_is_rejected_by_the_mac() {
    let vol = require_image!();

    // Same shape, same divisibility-by-11 property, one digit group changed.
    let wrong = "633281-498102-426096-319726-225203-245927-337876-444895";
    let err = match unlock_bitlocker(vol, &Credential::RecoveryKey(wrong.into())) {
        Ok(_) => panic!("a recovery password that is not this volume's must be refused"),
        Err(e) => e,
    };

    assert!(
        matches!(err, seance_plugin_bitlocker::BitlockerError::BadCredential),
        "must be rejected by the AES-CCM MAC, not by failing earlier; got {err:?}"
    );
}

/// The strongest assertion available: decrypt and check the plaintext is
/// structure **Windows wrote**, not merely that decryption returned bytes.
///
/// The relocated volume header must decrypt to an NTFS boot sector — `NTFS    `
/// at +3 and the `0x55AA` signature at +510. Those bytes are only recoverable
/// if the whole chain is right: recovery-password KDF, VMK unwrap, FVEK unwrap,
/// XTS key split, and the sector-to-tweak mapping. Any error anywhere yields
/// noise, so this is the assertion that ties the implementation to reality.
#[test]
fn the_relocated_volume_header_decrypts_to_a_real_ntfs_boot_sector() {
    let vol = require_image!();

    let unlocked =
        unlock_bitlocker(vol, &Credential::RecoveryKey(RECOVERY_PASSWORD.into())).expect("unlock");
    let plain = unlocked
        .decrypting_source
        .expect("XTS volume exposes a decrypting source");

    let mut boot = [0u8; 512];
    let n = plain
        .read_at(RELOCATED_HEADER_OFFSET, &mut boot)
        .expect("read the decrypted volume header");
    assert_eq!(n, 512);

    assert_eq!(
        &boot[3..11],
        b"NTFS    ",
        "the relocated header must decrypt to the NTFS OEM identifier; got {:?}",
        &boot[3..11]
    );
    assert_eq!(
        &boot[510..512],
        &[0x55, 0xAA],
        "the decrypted boot sector must end with the boot signature"
    );

    // A coherent BPB as well as the magic. A wrong key that happened to produce
    // the four bytes "NTFS" would not also produce a self-consistent BIOS
    // parameter block, so this is what separates decryption from coincidence.
    let bytes_per_sector = u16::from_le_bytes([boot[11], boot[12]]);
    assert_eq!(
        bytes_per_sector, 512,
        "BPB bytes-per-sector must be 512 on this volume"
    );
    assert!(
        boot[13].is_power_of_two(),
        "sectors-per-cluster must be a power of two, got {}",
        boot[13]
    );
}

/// **The property that makes the decrypted volume usable at all.**
///
/// On disk, sector 0 of a BitLocker volume is BitLocker's own VBR and the
/// filesystem's is relocated. A decrypting view that leaves it that way has
/// noise at offset 0, so every filesystem parser reads it, finds no `NTFS`
/// signature, and concludes the volume holds no filesystem — a fully recovered
/// volume that nothing can open, failing exactly as an unformatted disk would.
///
/// `unlock_bitlocker` therefore puts the relocated header back at the front,
/// and this is the assertion that it did.
#[test]
fn the_decrypted_volume_presents_a_mountable_ntfs_boot_sector_at_offset_zero() {
    let Some(plain) = decrypted_volume() else {
        eprintln!("skipping: corpus image not present");
        return;
    };

    let mut boot = [0u8; 512];
    plain.read_at(0, &mut boot).expect("read offset 0");

    assert_eq!(
        &boot[3..11],
        b"NTFS    ",
        "offset 0 of the decrypted volume must be the filesystem's own boot \
         sector, not BitLocker's; got {:?}",
        &boot[3..11]
    );
    assert_eq!(&boot[510..512], &[0x55, 0xAA]);

    // And the remap must not have shifted anything: a read straddling the end
    // of the relocated header has to continue with the volume's own bytes, or
    // one large read would silently splice two regions together.
    let mut straddle = vec![0u8; 16 * 1024];
    plain.read_at(0, &mut straddle).expect("straddling read");
    let mut direct = vec![0u8; 8 * 1024];
    plain.read_at(8192, &mut direct).expect("read past header");
    assert_eq!(
        &straddle[8192..16 * 1024],
        &direct[..],
        "a read crossing the end of the relocated header must continue with the \
         volume's real bytes at that offset"
    );
}

/// Decryption must hold well beyond the first sector. The MFT begins with the
/// `FILE` record signature; finding it at the offset the boot sector *claims*
/// ties two independently-decrypted regions together.
#[test]
fn the_master_file_table_decrypts_where_the_boot_sector_says_it_is() {
    let vol = require_image!();

    let unlocked =
        unlock_bitlocker(vol, &Credential::RecoveryKey(RECOVERY_PASSWORD.into())).expect("unlock");
    let plain = unlocked.decrypting_source.expect("decrypting source");

    let mut boot = [0u8; 512];
    plain
        .read_at(RELOCATED_HEADER_OFFSET, &mut boot)
        .expect("read boot sector");

    let bytes_per_sector = u16::from_le_bytes([boot[11], boot[12]]) as u64;
    let sectors_per_cluster = boot[13] as u64;
    let mft_cluster = u64::from_le_bytes(boot[48..56].try_into().unwrap());
    let mft_offset = mft_cluster * sectors_per_cluster * bytes_per_sector;

    let mut record = [0u8; 4];
    plain
        .read_at(mft_offset, &mut record)
        .expect("read decrypted MFT");

    assert_eq!(
        &record, b"FILE",
        "the MFT at the offset the boot sector names must decrypt to a FILE \
         record; a mismatch means decryption is correct only near sector 0"
    );
}

// ── a volume caught mid-conversion ─────────────────────────────────────────

/// Path to the same machine imaged while BitLocker was still converting,
/// paused at 56%.
fn partial_volume() -> Option<Arc<dyn DataSource>> {
    let p = corpus_path("SEANCE_WIN11_BITLOCKER_PARTIAL", "partial-encrypted.raw")?;
    let disk: Arc<dyn DataSource> = Arc::new(FileDataSource::new(p).ok()?);
    Some(Arc::new(WindowSource::new(
        disk,
        VOLUME_OFFSET,
        VOLUME_LENGTH,
    )))
}

/// **A volume mid-conversion must not read as unencrypted.**
///
/// Windows writes a different VBR identifier
/// (`92A84D3B-DD80-4D0E-9E4E-B1E3284EAED8`) while encryption is still running,
/// and swaps it for the standard one only when conversion completes. Matching
/// just the completed identifier reports a converting volume as not BitLocker —
/// and that is the state in which an examiner has the *best* chance of reading
/// plaintext, since much of the volume has not been encrypted yet.
#[test]
fn a_volume_still_converting_is_recognised_and_unlocks() {
    let Some(vol) = partial_volume() else {
        eprintln!("skipping: set SEANCE_WIN11_BITLOCKER_PARTIAL to the 56% image");
        return;
    };

    assert!(
        is_bitlocker(vol.as_ref()),
        "a volume paused mid-encryption must still be detected as BitLocker"
    );

    let unlocked = unlock_bitlocker(vol, &Credential::RecoveryKey(RECOVERY_PASSWORD.into()))
        .expect("the same recovery password must unlock the converting volume");
    assert_eq!(
        unlocked.encryption_method,
        EncryptionMethod::AesXts256,
        "the cipher is chosen before conversion starts and does not change"
    );
}

/// **The FVE metadata regions are plaintext on disk and must stay plaintext.**
///
/// BitLocker stores three redundant copies of its own metadata inside the
/// volume, and does not encrypt them — that is why they can be parsed without
/// any credential at all. A decrypting view that runs them through AES-XTS
/// anyway turns the one part of the volume that was always readable into noise.
///
/// The offsets are read from the VBR here rather than hardcoded, so this
/// asserts against what the volume says about itself.
#[test]
fn the_fve_metadata_regions_are_not_run_through_the_cipher() {
    let vol = require_image!();

    // The three metadata block offsets live at 0xb0 in a modern VBR.
    let mut boot = [0u8; 512];
    vol.read_at(0, &mut boot).expect("read the VBR");
    let offsets: Vec<u64> = (0..3)
        .map(|i| {
            let at = 0xb0 + i * 8;
            u64::from_le_bytes(boot[at..at + 8].try_into().unwrap())
        })
        .filter(|o| *o != 0)
        .collect();
    assert_eq!(
        offsets.len(),
        3,
        "this volume declares three metadata blocks"
    );

    let unlocked = unlock_bitlocker(
        Arc::clone(&vol),
        &Credential::RecoveryKey(RECOVERY_PASSWORD.into()),
    )
    .expect("unlock");
    let plain = unlocked.decrypting_source.expect("decrypting source");

    for (i, off) in offsets.iter().enumerate() {
        // What is genuinely on the disk there.
        let mut raw = [0u8; 8];
        vol.read_at(*off, &mut raw).expect("read raw");
        assert_eq!(
            &raw, b"-FVE-FS-",
            "block {i} at {off:#x} must carry the signature on disk"
        );

        // What the decrypted view shows there. It must be the same bytes: this
        // region was never encrypted, so decrypting it is not a translation,
        // it is damage.
        let mut seen = [0u8; 8];
        plain.read_at(*off, &mut seen).expect("read decrypted");
        assert_eq!(
            &seen, b"-FVE-FS-",
            "block {i} at {off:#x} is unencrypted on disk; the decrypted view \
             must pass it through, not cipher it into noise (got {seen:?})"
        );
    }
}

/// HUNT-239 on the real Windows 11 system volume, which — unlike the To Go
/// sample — the encryption detector also fingerprints (`-FVE-FS-` at offset
/// 3): the decryptor's locked record and its decrypted child both name the
/// volume by the `volume_artifact_id` the detector's record carries.
#[test]
fn the_real_volume_is_named_by_the_shared_volume_reference_locked_and_decrypted() {
    use seance_core::artifact::{Artifact, ArtifactType};
    use seance_core::module::ForensicsModule;
    use seance_plugin_bitlocker::BitlockerDecryptor;
    let vol = require_image!();
    let artifact = Artifact::new(
        uuid::Uuid::new_v4(),
        ArtifactType::Partition,
        Some(vol),
        serde_json::json!({ "name": "Partition 3" }),
    );
    let want = serde_json::json!(artifact.id.to_string());
    let locked = BitlockerDecryptor::new().process(&artifact).unwrap();
    assert_eq!(locked.len(), 1);
    assert_eq!(locked[0].metadata["subtype"], "detected_locked");
    assert_eq!(locked[0].metadata["volume_artifact_id"], want);
    let decrypted = BitlockerDecryptor::from_secrets(None, Some(RECOVERY_PASSWORD.into()))
        .process(&artifact)
        .unwrap();
    // The plaintext volume and the record saying it was unlocked (HUNT-120).
    assert_eq!(decrypted.len(), 2);
    assert!(decrypted[0].data.is_some());
    for record in &decrypted {
        assert_eq!(record.metadata["volume_artifact_id"], want);
    }
    assert_eq!(decrypted[1].metadata["credential_source"], "process_start");
}

// ── the recovery password supplied for this run (HUNT-120) ──────────────────

fn run_with_recovery_password(
    vol: Arc<dyn DataSource>,
    secret: &str,
) -> (Vec<Artifact>, Option<CredentialOutcome>) {
    let artifact = Artifact::new(
        uuid::Uuid::new_v4(),
        ArtifactType::Partition,
        Some(vol),
        serde_json::json!({ "name": "C:" }),
    );
    let cred = Arc::new(RunCredential::new(
        artifact.id,
        CredentialKind::BitlockerRecoveryPassword,
        secret.to_string(),
        "erin",
    ));
    let out = credential::scoped(Some(cred.clone()), || {
        BitlockerDecryptor::new()
            .process(&artifact)
            .expect("process")
    });
    (out, cred.outcome())
}

/// The 48-digit recovery password, typed into the attention queue after
/// ingest, opens the real Windows 11 system volume: the module holds no
/// process-level credential, and the child volume presents NTFS at offset 0.
#[test]
fn a_recovery_password_supplied_for_this_run_unlocks_the_real_volume() {
    let vol = require_image!();
    let (out, outcome) = run_with_recovery_password(vol, RECOVERY_PASSWORD);
    assert_eq!(outcome, Some(CredentialOutcome::Accepted));
    assert_eq!(out.len(), 2);
    let plain = out[0].data.as_ref().expect("a decrypting source");
    let mut boot = [0u8; 512];
    plain.read_at(0, &mut boot).expect("read");
    assert_eq!(
        &boot[3..11],
        b"NTFS    ",
        "the decrypted volume presents NTFS"
    );
    assert_eq!(out[1].metadata["status"], "Unlocked");
    assert_eq!(
        out[1].metadata["credential_kind"],
        "bitlocker_recovery_password"
    );
    for a in &out {
        assert!(!a.metadata.to_string().contains(RECOVERY_PASSWORD));
    }
}

/// A well-formed recovery password that is not this volume's is refused.
#[test]
fn a_wrong_recovery_password_supplied_for_this_run_is_rejected() {
    let vol = require_image!();
    // Every group divisible by 11: well formed, and not this volume's.
    let (out, outcome) = run_with_recovery_password(
        vol,
        "000011-000022-000033-000044-000055-000066-000077-000088",
    );
    assert!(
        matches!(outcome, Some(CredentialOutcome::Rejected { .. })),
        "{outcome:?}"
    );
    assert_eq!(out.len(), 1);
    assert_eq!(out[0].metadata["status"], "UnlockFailed");
}
