impl FileSignature for TxtSignature {
    fn name(&self) -> &str {
        "TXT"
    }
    fn extensions(&self) -> &[&str] {
        &["tx?"]
    }

    fn header_check(&self, buf: &[u8], _offset: usize) -> Option<RecoveryInit> {
        for &(magic, ext) in FASTTXT_MAGICS {
            if buf.len() >= magic.len() && &buf[0..magic.len()] == magic {
                // PhotoRec's header_check_fasttxt rejects a match immediately
                // followed by a NUL byte (not real text).
                if buf.len() > magic.len() && buf[magic.len()] == 0 {
                    return None;
                }
                return Some(RecoveryInit {
                    min_filesize: magic.len() as u64 + 1,
                    extension: ext.to_string(),
                    calculated_file_size: None,
                });
            }
        }
        None
    }

    fn data_check(&self, buf: &[u8], recovery: &mut FileRecovery) -> DataCheckResult {
        // A header match is a claim; the header block is where it is checked
        // (CARVE-015). Refusing it here keeps a stray magic from ending a
        // carve already running and from starting a carve of its own.
        if recovery.file_size == 0 && !header_block_plausible(buf) {
            return DataCheckResult::Error;
        }
        // PhotoRec uses data_check_txt to stop at the first non-text run; that
        // stateful text validator is not implemented.
        DataCheckResult::Continue
    }

    fn file_check(&self, _data: &[u8], _recovery: &mut FileRecovery) {}

    fn max_file_size(&self) -> u64 {
        100 * 1024 * 1024
    }
}

/// A text file's first block is text: no control bytes other than tab, line
/// feed, vertical tab, form feed, carriage return and escape, and no NUL
/// except as the zero padding after a file shorter than the block. Its bytes
/// above 0x7F are either UTF-8 (a sequence cut by the block's end allowed) or
/// the scattering of accented letters of a single-byte code page, not the
/// majority of the block.
fn header_block_plausible(buf: &[u8]) -> bool {
    let end = buf.iter().rposition(|&b| b != 0).map_or(0, |i| i + 1);
    let text = &buf[..end];
    if !text
        .iter()
        .all(|&b| b >= 0x20 || matches!(b, b'\t' | b'\n' | 0x0B | 0x0C | b'\r' | 0x1B))
    {
        return false;
    }
    let utf8 = match std::str::from_utf8(text) {
        Ok(_) => true,
        // Only a multi-byte sequence the block boundary cut short.
        Err(e) => e.error_len().is_none(),
    };
    utf8 || text.iter().filter(|&&b| b >= 0x80).count() * 4 <= text.len()
}

pub fn register(registry: &mut SignatureRegistry) {
    for &(magic, _ext) in FASTTXT_MAGICS {
        registry.register(0, magic, Arc::new(TxtSignature));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_txt_header_match() {
        let sig = TxtSignature;
        // "#!/bin/sh\n" -> sh
        let init = sig.header_check(b"#!/bin/sh\necho hi", 0).unwrap();
        assert_eq!(init.extension, "sh");
        // RSA private key -> key
        let init2 = sig
            .header_check(b"-----BEGIN RSA PRIVATE KEY-----\nMIIE", 0)
            .unwrap();
        assert_eq!(init2.extension, "key");
    }

    #[test]
    fn test_txt_no_match() {
        let sig = TxtSignature;
        assert!(sig.header_check(b"this is just plain text", 0).is_none());
        // magic immediately followed by NUL is rejected
        assert!(sig.header_check(b"REGEDIT4\x00", 0).is_none());
    }
}
